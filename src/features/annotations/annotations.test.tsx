import { expect, it, vi } from 'vitest';
import { fireEvent, render, screen } from '@testing-library/react';
import fixture from '../../../tests/fixtures/document-v3.json';
import { parseProjectDocument } from '../../bridge/types';
import { AnnotationInspector } from './AnnotationInspector';
import { CategoryManager } from './CategoryManager';
import { AnnotationList } from './AnnotationList';
it('displays readable numeric precision without writing rounded geometry on focus or blur', () => {
  const doc = parseProjectDocument(fixture), annotation = { ...doc.annotations[0], region: { ...doc.annotations[0].region, startSeconds: .200000016, lowHz: 469.6729297 } };
  const write = vi.fn(), mutate = vi.fn(), submit = vi.fn(async () => {});
  const ui = { active: { store: { snapshot: { document: doc }, editingDisabled: false }, lifecycle: { subscribe: () => () => {}, getVersion: () => 0 } }, drafts: { read: () => undefined, write, submit }, mutate };
  render(<AnnotationInspector ui={ui as never} annotation={annotation} />);
  const time = screen.getByLabelText('开始（秒）'), hz = screen.getByLabelText('下界（Hz）');
  expect(time).toHaveValue(.2); expect(hz).toHaveValue(469.67);
  fireEvent.focus(time); fireEvent.blur(time); fireEvent.focus(hz); fireEvent.blur(hz);
  expect(write).not.toHaveBeenCalled(); expect(mutate).not.toHaveBeenCalled();
  expect(annotation.region.startSeconds).toBe(.200000016); expect(annotation.region.lowHz).toBe(469.6729297);
});
it('rejects duplicate trimmed category names and requires affected-count confirmation', () => {
  const doc = parseProjectDocument(fixture), command = vi.fn();
  render(<CategoryManager ui={{ active: { store: { snapshot: { document: doc }, editingDisabled: false } }, command } as never} />);
  fireEvent.change(screen.getByLabelText('类别名称'), { target: { value: ' 鸟声 ' } });
  expect(screen.getByRole('button', { name: '添加类别' })).toBeDisabled();
  fireEvent.click(screen.getByLabelText('删除类别 鸟声'));
  expect(screen.getByRole('alertdialog')).toHaveTextContent('1 个区域将移除此标签'); expect(command).not.toHaveBeenCalled();
  fireEvent.click(screen.getByRole('button', { name: '确认删除类别' }));
  expect(command).toHaveBeenCalledWith({ type: 'removeCategory', id: doc.categories[0].id });
});
it('combines category/channel/note filters and locates the exact media and channel', () => {
  const doc = parseProjectDocument(fixture), onLocate = vi.fn(), a = doc.annotations[0];
  doc.annotations.push({ ...a, id: 'second', categoryIds: [], region: { ...a.region, channelIndex: 0 }, note: 'another' });
  render(<AnnotationList doc={doc} selectedId={null} onLocate={onLocate} />);
  fireEvent.change(screen.getByLabelText('筛选类别'), { target: { value: a.categoryIds[0] } });
  fireEvent.change(screen.getByLabelText('筛选通道'), { target: { value: '1' } });
  fireEvent.change(screen.getByLabelText('筛选备注'), { target: { value: '区域' } });
  expect(screen.getAllByRole('button')).toHaveLength(1); fireEvent.click(screen.getByRole('button'));
  expect(onLocate).toHaveBeenCalledWith(expect.objectContaining({ scope: 'region', annotation: a }));
  fireEvent.change(screen.getByLabelText('筛选通道'), { target: { value: '0' } });
  expect(screen.queryByRole('button')).not.toBeInTheDocument();
});
