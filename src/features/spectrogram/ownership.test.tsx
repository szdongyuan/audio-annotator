import { act, renderHook } from '@testing-library/react';
import { it, expect, vi } from 'vitest';
import fixture from '../../../tests/fixtures/document-v1.json';
import { parseProjectDocument } from '../../bridge/types';
import { ProjectStore } from '../../app/store';
import { CommandQueue, type ProjectCommands } from '../../app/commands';
import { ProjectLifecycle } from '../project/lifecycle';
import { useWorkspace } from './useWorkspace';
import { TileScheduler } from './tileScheduler';
it('coalesces the last view into lifecycle save, serializes it, and rejects edits during transition', async () => {
  const store = new ProjectStore({ document: parseProjectDocument(fixture), canUndo: false, canRedo: false });
  const apply = vi.fn<ProjectCommands['applyChange']>(async (_id, revision, change) => ({ ...store.snapshot, document: { ...store.snapshot.document, revision: revision + 1, ...(change.type === 'updateViewState' ? { viewState: change.viewState } : {}) } }));
  const queue = new CommandQueue(store, { applyChange: apply } as unknown as ProjectCommands);
  const save = vi.fn(async (_id: string, revision: number) => revision);
  const lifecycle = new ProjectLifecycle(store, queue, { save, close: vi.fn() });
  const active = { store, queue, lifecycle, path: 'project' }, id = fixture.media[0].id;
  const hook = renderHook(() => useWorkspace(active, id));
  act(() => { hook.result.current.patch(id, { gainDb: 3 }); hook.result.current.patch(id, { gainDb: 12, visibleChannels: [1], endSeconds: 1 }); });
  await act(() => lifecycle.save());
  expect(apply).toHaveBeenCalledTimes(1); expect(store.snapshot.document.viewState.media[id]).toMatchObject({ gainDb: 12, visibleChannels: [1], endSeconds: 1 });
  expect(store.drafts.size).toBe(0); expect(save).toHaveBeenCalledWith(fixture.projectId, 1);
  const release = store.beginTransition(); act(() => hook.result.current.patch(id, { gainDb: 40 }));
  expect(store.drafts.size).toBe(0); expect(hook.result.current.view(id).gainDb).toBe(12);
  release(); hook.unmount(); lifecycle.dispose();
});
it('bounds native concurrency across panes and drops cancelled queued work', async () => {
  const scheduler = new TileScheduler();
  const releases: (() => void)[] = [], started: number[] = [];
  let valid = true;
  for (let i = 0; i < 12; i++) scheduler.submit(true, () => i < 4 || valid, async () => { started.push(i); await new Promise<void>(resolve => releases.push(resolve)); });
  expect(started).toEqual([0, 1, 2, 3]); valid = false;
  releases.forEach(release => release()); await new Promise(resolve => setTimeout(resolve, 0));
  expect(started).toEqual([0, 1, 2, 3]);
});
it('reconciles history media removal before submitting pending views without losing valid drafts', async () => {
  const document = parseProjectDocument(fixture), id = document.media[0].id;
  const other = { ...document.media[0], id: '22222222-2222-4222-8222-222222222222' };
  document.media.push(other);
  const store = new ProjectStore({ document, canUndo: true, canRedo: false });
  const apply = vi.fn<ProjectCommands['applyChange']>(async (_id, revision, change) => ({ ...store.snapshot, document: { ...store.snapshot.document, revision: revision + 1, ...(change.type === 'updateViewState' ? { viewState: change.viewState } : {}) } }));
  const queue = new CommandQueue(store, { applyChange: apply } as unknown as ProjectCommands);
  const lifecycle = new ProjectLifecycle(store, queue, { save: async (_, r) => r, close: vi.fn() });
  const active = { store, queue, lifecycle, path: '' };
  const hook = renderHook(() => useWorkspace(active, id));
  act(() => { hook.result.current.patch(id, { gainDb: 12 }); hook.result.current.compare(other.id); });
  act(() => store.accept({ ...store.snapshot, document: { ...store.snapshot.document, revision: 1, media: [document.media[0]], viewState: { ...document.viewState, compareMediaId: null } } }));
  await act(() => lifecycle.submitDrafts());
  const view = store.snapshot.document.viewState;
  expect(view.compareMediaId).toBeNull(); expect(view.media[other.id]).toBeUndefined(); expect(view.media[id].gainDb).toBe(12);
  hook.unmount(); lifecycle.dispose();
});
